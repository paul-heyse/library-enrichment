"""Make the installed binaries describe themselves.

Everything here comes from a pinned binary's own output, never from a recollection of what a
flag does. That is the point: a reference built from documentation describes the tool the
documentation was written for, while a reference built from `--help` describes the tool that
will actually execute.

Three oracles are unusually load-bearing:

* `rg --generate man` emits the complete roff manual from the binary itself, already divided
  into REGEX SYNTAX / EXIT STATUS / AUTOMATIC FILTERING / CONFIGURATION FILES / CAVEATS. It is
  the text the project ships as its man page, so it cannot lag the binary.
* `rg --help` groups every flag under INPUT / SEARCH / FILTER / OUTPUT / OUTPUT MODES / LOGGING /
  OTHER BEHAVIORS. That grouping is upstream's own functional taxonomy, and the use-case router
  is built on it rather than on one invented here.
* ast-grep does **not** enumerate its languages: `-l` documents itself with a link to a web page.
  So the language roster is established by probing the binary with candidate names and recording
  which it accepts. An accepted name is evidence; a rejected one is evidence of rejection by
  this binary, not proof that no such parser exists anywhere.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

Flag = dict[str, str]


class OracleMissing(RuntimeError):
    """A pinned binary is not on PATH, so it cannot be asked to describe itself."""


def _require(binary: str) -> str:
    found = shutil.which(binary)
    if not found:
        raise OracleMissing(
            f"{binary!r} is not on PATH. This repository is built from the installed binaries; "
            f"it cannot be produced from documentation alone."
        )
    return found


def run(
    binary: str,
    *args: str,
    stdin: str | None = None,
    check: bool = True,
) -> tuple[int, str, str]:
    """Run a pinned binary and return (exit code, stdout, stderr)."""
    _require(binary)
    proc = subprocess.run(
        [binary, *args],
        input=stdin,
        capture_output=True,
        text=True,
        errors="replace",
        check=False,
    )
    if check and proc.returncode != 0:
        raise OracleMissing(
            f"{binary} {' '.join(args)} exited {proc.returncode}: {proc.stderr[:400]}"
        )
    return proc.returncode, proc.stdout, proc.stderr


# --------------------------------------------------------------------------- versions


def tool_versions() -> dict[str, object]:
    """Record what is actually installed, including the PCRE2 discrepancy.

    `rg --pcre2-version` prints a constant compiled in from the PCRE2 headers at ripgrep's build
    time. It is a claim about the build, never a measurement of the runtime: a dynamically linked
    binary runs against whatever shared library it resolves. On the machine this was built for it
    reads 10.45 while the linked library is 10.48 -- three releases of drift.

    It is recorded anyway, and deliberately, because an agent that reads it will be wrong, and
    the repository's job is to show why rather than to quietly substitute a better answer.
    """
    _, ag, _ = run("ast-grep", "--version")
    _, rgv, _ = run("rg", "--version")
    _, pcre, _ = run("rg", "--pcre2-version")

    features = ""
    for line in rgv.splitlines():
        if line.startswith("features:"):
            features = line.split(":", 1)[1].strip()

    return {
        "ast_grep": ag.strip(),
        "ripgrep": rgv.splitlines()[0].strip() if rgv.strip() else "",
        "ripgrep_features": features,
        "pcre2_build_string": _pcre2_number(pcre),
        "pcre2_build_string_raw": pcre.strip(),
        "pcre2_jit": "JIT is available" in pcre,
        **pcre2_runtime(),
    }


def _pcre2_number(text: str) -> str:
    match = re.search(r"PCRE2 (\d+\.\d+)", text)
    return match.group(1) if match else ""


# --------------------------------------------------------------------------- ripgrep


RG_CATEGORY_RE = re.compile(r"^([A-Z][A-Z0-9 /-]+):$")
RG_FLAG_RE = re.compile(r"^ {4}(-.+)$")


def ripgrep_man() -> str:
    """Return the complete roff manual, generated by the binary that will execute."""
    _, out, _ = run("rg", "--generate", "man")
    return out


def ripgrep_help() -> str:
    """Return the long-form help text of the installed ripgrep."""
    _, out, _ = run("rg", "--help")
    return out


def ripgrep_flags() -> list[Flag]:
    """Parse `rg --help` into flag records, keeping upstream's own category for each.

    The category is what the use-case router routes on, so it is carried through verbatim
    rather than remapped into a taxonomy of our own.
    """
    flags: list[Flag] = []
    category = ""
    current: Flag | None = None
    body: list[str] = []

    def flush() -> None:
        nonlocal current, body
        if current is not None:
            current["summary"] = _first_sentence(body)
            current["doc"] = "\n".join(body).strip()
            flags.append(current)
        current, body = None, []

    for line in ripgrep_help().splitlines():
        cat = RG_CATEGORY_RE.match(line)
        if cat:
            flush()
            category = cat.group(1)
            continue
        flag = RG_FLAG_RE.match(line)
        if flag and category:
            flush()
            current = {
                "tool": "rg",
                "command": "rg",
                "category": category,
                "values": "",
                **_parse_rg_spec(flag.group(1)),
            }
            continue
        if current is not None:
            body.append(line.strip())
    flush()
    return flags


def _parse_rg_spec(spec: str) -> Flag:
    """Split a ripgrep help spec such as `-e PATTERN, --regexp=PATTERN` into parts."""
    short, long, arg = "", "", ""
    for part in [p.strip() for p in spec.split(",")]:
        if part.startswith("--"):
            name, _, value = part.partition("=")
            long = name[2:]
            arg = value or arg
        elif part.startswith("-"):
            short = part[1:2]
            rest = part[2:].strip()
            if rest:
                arg = rest
    return {"long": long, "short": short, "arg": arg}


def ripgrep_type_list() -> list[tuple[str, str]]:
    """Return every file type this binary knows, as (type, globs)."""
    _, out, _ = run("rg", "--type-list")
    rows = []
    for line in out.splitlines():
        name, sep, globs = line.partition(":")
        if sep:
            rows.append((name.strip(), globs.strip()))
    return rows


def ripgrep_man_section(name: str) -> str:
    """Extract one .SH section from the generated manual."""
    man = ripgrep_man()
    pattern = re.compile(
        r"^\.SH " + re.escape(name) + r"$(.*?)(?=^\.SH |\Z)", re.MULTILINE | re.DOTALL
    )
    match = pattern.search(man)
    return match.group(1).strip() if match else ""


# --------------------------------------------------------------------------- ast-grep


AG_FLAG_RE = re.compile(r"^ {2,6}(-{1,2}[A-Za-z].*)$")
AG_ARG_RE = re.compile(r"[<\[]([^>\]]+)[>\]]")


def ast_grep_commands() -> list[str]:
    """Return the subcommands this binary exposes, read from its own help."""
    _, out, _ = run("ast-grep", "--help")
    found: list[str] = []
    in_commands = False
    for line in out.splitlines():
        if line.startswith("Commands:"):
            in_commands = True
            continue
        if in_commands:
            if not line.strip() or line.startswith("Options:"):
                break
            name = line.strip().split()[0]
            if name.isalpha():
                found.append(name)
    return found


def ast_grep_flags() -> list[Flag]:
    """Parse each subcommand's `--help` into flag records, carrying enum values."""
    flags: list[Flag] = []
    for command in ast_grep_commands():
        code, out, _ = run("ast-grep", command, "--help", check=False)
        if code != 0:
            continue
        flags.extend(_parse_ag_command_help(command, out))
    return flags


def _parse_ag_command_help(command: str, out: str) -> list[Flag]:
    """Parse one subcommand's help body into flag records."""
    flags: list[Flag] = []
    current: Flag | None = None
    body: list[str] = []

    def flush() -> None:
        nonlocal current, body
        if current is not None:
            current["summary"] = _first_sentence(body)
            current["values"] = ",".join(_enum_values(body))
            current["doc"] = "\n".join(body).strip()
            flags.append(current)
        current, body = None, []

    in_options = False
    for line in out.splitlines():
        if line.startswith("Options:"):
            in_options = True
            continue
        if not in_options:
            continue
        match = AG_FLAG_RE.match(line)
        if match:
            flush()
            current = {
                "tool": "ast-grep",
                "command": f"ast-grep {command}",
                "category": "",
                **_parse_ag_spec(match.group(1)),
            }
            continue
        if current is not None:
            body.append(line.strip())
    flush()
    return flags


def _parse_ag_spec(spec: str) -> Flag:
    """Split an ast-grep clap spec such as `-p, --pattern <PATTERN>` into parts."""
    short, long, arg = "", "", ""
    head = spec.split("  ")[0].strip()
    for raw in [p.strip() for p in head.split(",")]:
        part = raw
        arg_match = AG_ARG_RE.search(part)
        if arg_match:
            arg = arg_match.group(1)
            part = part[: arg_match.start()].strip()
        part = part.rstrip("=[")
        if part.startswith("--"):
            long = part[2:]
        elif part.startswith("-"):
            short = part[1:2]
    return {"long": long, "short": short, "arg": arg}


def _enum_values(body: list[str]) -> list[str]:
    """Pull `Possible values:` enum members out of a clap help body."""
    values: list[str] = []
    collecting = False
    for line in body:
        if line.startswith("Possible values:"):
            collecting = True
            continue
        if collecting:
            if line.startswith("- "):
                values.append(line[2:].split(":")[0].strip())
            elif line and not line.startswith("-") and values:
                break
    return values


