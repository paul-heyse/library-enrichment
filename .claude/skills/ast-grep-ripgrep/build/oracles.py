def ast_grep_languages() -> dict[str, bool]:
    """Probe which language names this binary accepts.

    `ast-grep --help` does not enumerate languages; it links to a web page that has historically
    lagged the binary. Probing is the only oracle that describes the installed parser set.
    """
    accepted: dict[str, bool] = {}
    for name in AG_LANGUAGE_CANDIDATES:
        code, _, _ = run(
            "ast-grep", "run", "--stdin", "-l", name, "-p", "x", check=False, stdin="x\n"
        )
        # 0 = matched, 1 = ran and found nothing. Both mean the language was accepted.
        accepted[name] = code in (0, 1)
    return accepted


def _first_sentence(body: list[str]) -> str:
    for line in body:
        text = line.strip()
        if text and not text.startswith("-"):
            return re.split(r"(?<=[.!?])\s", text)[0].strip()
    return ""


# --------------------------------------------------------------------------- PCRE2 runtime

# PCRE2 ships a documented conditional whose comparison is compiled inside `pcre2_compile()` --
# that is, inside libpcre2 itself. So it reports the *linked library*, not the headers ripgrep
# was built against and not a filesystem path. Upstream's comparison code is byte-identical
# across 10.47 and 10.48, so the probe cannot be confounded by a change to the probe mechanism.
PCRE2_VERSION_ASSERT = "(?(VERSION={version}).|(*FAIL))"

_LDD_PCRE2_RE = re.compile(r"libpcre2-8[^\s]*\s+=>\s+(\S+)")
_SO_VERSION_RE = re.compile(rb"\b(10\.\d{1,3} \d{4}-\d{2}-\d{2})\b")
_UNICODE_RE = re.compile(r"Unicode version (\d+\.\d+\.\d+)")


def pcre2_asserts(version: str) -> bool:
    """Ask the linked PCRE2 whether it is exactly `version`.

    Exit 0 means the conditional took the matching branch, so the library agrees. Exit 1 means it
    took `(*FAIL)`. Exit 2 would mean the pattern did not compile, which is a different answer
    again and is reported as a failed assertion rather than silently as "no".
    """
    code, _, _ = run(
        "rg", "-qP", PCRE2_VERSION_ASSERT.format(version=version), check=False, stdin="x\n"
    )
    return code == 0


def pcre2_runtime() -> dict[str, str]:
    """Resolve the PCRE2 ripgrep actually links, and read its version from the library itself.

    Three readings, each labelled by how it was obtained, because they answer different questions
    and can legitimately disagree:

    * `pcre2_linked_library` / `pcre2_linked_version` -- which file, and the version string
      embedded in it. Read with the standard library alone; no `strings` binary required.
    * `pcre2_unicode_version` -- which Unicode tables it carries, from `pcre2test -C` beside it.
    * `pcre2_resolution` -- how the above were obtained, or why they could not be.

    This degrades rather than lying. `ldd` is Linux-only, a statically linked ripgrep has no
    object to resolve, and a library at /usr/lib carries no version in its path. When resolution
    fails every field is empty and `pcre2_resolution` says so, leaving the version assertion as
    the authority.
    """
    blank = {
        "pcre2_linked_library": "",
        "pcre2_linked_version": "",
        "pcre2_unicode_version": "",
        "pcre2_resolution": "unresolved",
    }

    rg_path = shutil.which("rg")
    if not rg_path or not shutil.which("ldd"):
        return blank

    code, out, _ = run("ldd", rg_path, check=False)
    if code != 0:
        return blank
    match = _LDD_PCRE2_RE.search(out)
    if not match:
        # A static build, or PCRE2 compiled in. Not an error: just not resolvable this way.
        return {**blank, "pcre2_resolution": "static-or-absent"}

    library = Path(match.group(1))
    result = dict(blank)
    result["pcre2_linked_library"] = str(library)
    result["pcre2_resolution"] = "ldd"

    try:
        payload = library.read_bytes()
    except OSError:
        return result

    found = _SO_VERSION_RE.search(payload)
    if found:
        result["pcre2_linked_version"] = found.group(1).decode()
        result["pcre2_resolution"] = "ldd+embedded-string"

    # pcre2test, when installed beside the library, is the only thing that reports the Unicode
    # tables. It is frequently absent, and its absence is recorded rather than guessed around.
    pcre2test = library.parent.parent / "bin" / "pcre2test"
    if pcre2test.exists():
        code, out, _ = run(str(pcre2test), "-C", check=False)
        unicode_match = _UNICODE_RE.search(out)
        if code == 0 and unicode_match:
            result["pcre2_unicode_version"] = unicode_match.group(1)
    return result
