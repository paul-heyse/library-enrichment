"""Rules derived from the pinned data, rather than written by hand.

`project-removed-constructor-kwarg` is the highest-yield rule this repository ships -- the 4.0
constructor keywords still read correctly, still pass most type checkers, and raise only when the
server is constructed. It was also a hand-typed alternation, exact on the day it was written and
silently wrong at the next re-pin. The keyword list already exists as data: `catalogs.py` parses
`_REMOVED_KWARGS` straight out of upstream's source, so generating the rule from that keeps it
exact for free.

Generated rules are written to `rules/generated/` and are never hand-edited. Every one gets a
test case built from the same data, because a rule with no invalid fixture can stop matching
without anything failing -- and `ast-grep test` counts executed cases, not real hits.
"""

from __future__ import annotations

import re
from pathlib import Path

HEADER = "# Generated by build/queries.py from the pinned model. Do not edit by hand.\n\n"

ROW = re.compile(r"^\|\s*`([a-z_][a-z0-9_]*)`\s*\|\s*(.+?)\s*\|$", re.MULTILINE)


def _removed_kwargs(content: Path) -> list[tuple[str, str]]:
    """Read the removed-keyword table back out of the catalog the build just wrote."""
    catalog = content / "catalogs" / "removed-api.md"
    if not catalog.is_file():
        raise SystemExit("catalogs/removed-api.md must be written before queries.py runs")
    rows = ROW.findall(catalog.read_text())
    if not rows:
        raise SystemExit(
            "no rows parsed from catalogs/removed-api.md -- the table shape changed, and a "
            "generated rule with an empty alternation would match nothing while looking fine"
        )
    return sorted(rows)


def removed_constructor_kwarg(content: Path) -> tuple[str, str, str]:
    """Return `(rule id, rule yaml, test yaml)` for the removed-keyword check."""
    rows = _removed_kwargs(content)
    names = [name for name, _ in rows]
    alternation = "|".join(names)
    sample = ", ".join(f"`{name}`" for name in names[:6])
    example = names[0]
    replacement = dict(rows)[example]

    rule = (
        HEADER
        + f"""id: project-removed-constructor-kwarg
language: python
severity: hint
message: This `FastMCP(...)` keyword was removed in 4.0 and now raises TypeError.
note: |
  {len(names)} constructor keywords were moved out of `FastMCP()` in 4.0. The call still reads
  correctly and most type checkers still accept it; it raises only when the server is
  constructed. That combination is why this is the highest-yield check here.

  Removed: {sample}{"..." if len(names) > 6 else ""}
  Full table with upstream's own replacement text: content/catalogs/removed-api.md

  Host, port, paths and transport flags belong on `run_http_async()` or `http_app()`, or in
  `FASTMCP_*` environment variables. Tag filtering became `server.enable(...)` and
  `server.disable(...)`. Tool transformation became `server.add_transform(...)`.

  Matches by keyword name on a call to something spelled `FastMCP`, so a constructor of your
  own taking a `port=` would match. ast-grep resolves no imports.
metadata:
  record: removed-api
  capability: server-construction
  generated: true
rule:
  kind: call
  all:
    - has:
        field: function
        regex: '(^|\\.)FastMCP$'
    - has:
        kind: keyword_argument
        stopBy: end
        has:
          field: name
          regex: '^({alternation})$'
"""
    )

    test = f"""# Generated by build/queries.py. The invalid case is built from the same table as
# the rule, so the two cannot drift apart.
id: project-removed-constructor-kwarg
valid:
  - |
    mcp = FastMCP(name="demo", instructions="hello")
  - |
    mcp.run_http_async(host="0.0.0.0", port=8000)
invalid:
  - |
    mcp = FastMCP(name="demo", {example}=True)
"""
    # The replacement text is not asserted, only recorded, so a reader of the fixture can see
    # what upstream says to do instead without opening the catalog.
    test += f"# upstream's replacement for `{example}`: {replacement}\n"
    return "project-removed-constructor-kwarg", rule, test


def generate(content: Path, queries: Path) -> int:
    """Write every generated rule and its fixture. Returns the number written."""
    out = queries / "rules" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    tests = queries / "rule-tests"
    tests.mkdir(parents=True, exist_ok=True)

    written = 0
    for rule_id, rule, test in (removed_constructor_kwarg(content),):
        (out / f"{rule_id}.yml").write_text(rule)
        (tests / f"{rule_id}-test.yml").write_text(test)
        written += 1
    return written
