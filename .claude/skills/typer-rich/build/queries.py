"""Write the `project-*` rules from data this build produced, never by hand.

fastmcp generates one rule by parsing its own `removed-api.md` back out. The contract transfers;
the data source does not, because neither of these libraries carries an in-source table of what
it removed.

Two sources here, and the split matters. The Typer rules are generated from `current_facts` --
present-tense statements about the pinned release -- because this repository describes Typer
0.27.2 and says nothing about earlier versions. The Rich rule is generated from a
breaking-change row, because Rich's own history is still in scope.

Either way the rule is derived rather than typed, so it cannot describe a symbol this pin does
not have, and a re-pin that changes the surface changes the rule with it.

Three rules, each aimed at a failure that survives a type checker:

  project-vendored-click-import  `import click` in a Typer project. Typer 0.27.2 carries its own
                                 copy and does not depend on the distribution, so the import
                                 resolves to a different library -- if it resolves at all -- and
                                 it type-checks either way.
  project-typer-slim-install     a `typer-slim` dependency, which pulls Rich regardless.
  project-rich-version-attr      `rich.__version__`, removed in 14.3.4 and an AttributeError now.

All are `severity: hint` and none carries a `fix`. They are questions about your code, not
proven defects: ast-grep resolves no imports and no types, so a hit is a place to look.
"""

from __future__ import annotations

import json
from pathlib import Path

HEADER = (
    "# Generated by build/queries.py from catalogs.json and the model.\n"
    "# Do not hand-edit: a re-pin rewrites this file, and a hand-edit would be lost silently.\n"
)


class QueryError(RuntimeError):
    """The generated rules could not be produced from real data."""


def _rule(rule_id: str, message: str, note: str, body: str) -> str:
    # The message is JSON-quoted rather than written as a plain scalar. Every message here starts
    # with a backtick around a symbol name, and YAML reserves `` ` `` as an indicator character:
    # a plain scalar may not begin with one. ast-grep reports that as "found character that
    # cannot start any token", which reads like a rule-syntax error rather than a quoting one.
    return (
        f"{HEADER}id: {rule_id}\n"
        "language: python\n"
        "severity: hint\n"
        f"message: {json.dumps(message)}\n"
        f"note: |\n{note}\n"
        "metadata:\n"
        "  generated: true\n"
        "  source: catalogs.json\n"
        f"rule:\n{body}\n"
    )


def _indent(text: str, spaces: int = 2) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else "" for line in text.strip().splitlines())


def write_all(rows: list[dict], rules_dir: Path, tests_dir: Path) -> int:
    """Generate every rule a row or a fact names, plus its fixtures."""
    named = {row["rule"] for row in rows if row.get("rule", "-") != "-"}
    if not named:
        raise QueryError(
            "no breaking-change row names a rule; the generated rules would be empty, which is "
            "indistinguishable from a clean project when the scan runs"
        )

    rules_dir.mkdir(parents=True, exist_ok=True)
    tests_dir.mkdir(parents=True, exist_ok=True)
    written = 0

    by_id = {row["rule"]: row for row in rows if row.get("rule", "-") != "-"}

    if "project-vendored-click-import" in named:
        row = by_id["project-vendored-click-import"]
        # Taken from the fact record rather than retyped, so a re-pin that restates the fact
        # restates the rule with it.
        consequence = row.get("consequence", "")
        (rules_dir / "project-vendored-click-import.yml").write_text(
            _rule(
                "project-vendored-click-import",
                "`click` is imported in a project that uses Typer.",
                _indent(
                    f"{row['fact']}\n\n"
                    f"{consequence}\n\n"
                    f"Evidence: {row.get('evidence', '')}\n\n"
                    "If you need what the import gave you, see "
                    "`content/catalogs/vendored-click.md` for what Typer re-exports and what it "
                    "does not."
                ),
                _indent(
                    "any:\n"
                    "  - pattern: import click\n"
                    "  - pattern: import click as $ALIAS\n"
                    "  - pattern: from click import $$$NAMES\n"
                    "  - pattern: from click.$MOD import $$$NAMES",
                    2,
                ),
            )
        )
        (tests_dir / "project-vendored-click-import-test.yml").write_text(
            "id: project-vendored-click-import\n"
            "valid:\n"
            "  - |\n"
            "    import typer\n"
            "    app = typer.Typer()\n"
            "  - |\n"
            "    from typer import Context\n"
            "invalid:\n"
            "  - |\n"
            "    import click\n"
            "  - |\n"
            "    from click import Command\n"
        )
        written += 1

    if "project-typer-slim-install" in named:
        row = by_id["project-typer-slim-install"]
        (rules_dir / "project-typer-slim-install.yml").write_text(
            _rule(
                "project-typer-slim-install",
                "`typer_slim` is imported; it is a wrapper around `typer` and saves nothing.",
                _indent(f"{row['fact']}\n\n{row.get('consequence', '')}"),
                _indent(
                    "any:\n"
                    "  - pattern: import typer_slim\n"
                    "  - pattern: import typer_slim as $ALIAS\n"
                    "  - pattern: from typer_slim import $$$NAMES",
                    2,
                ),
            )
        )
        (tests_dir / "project-typer-slim-install-test.yml").write_text(
            "id: project-typer-slim-install\n"
            "valid:\n"
            "  - |\n"
            "    import typer\n"
            "invalid:\n"
            "  - |\n"
            "    import typer_slim\n"
        )
        written += 1

    if "project-rich-version-attr" in named:
        row = by_id["project-rich-version-attr"]
        (rules_dir / "project-rich-version-attr.yml").write_text(
            _rule(
                "project-rich-version-attr",
                "`rich.__version__` does not exist; this raises AttributeError.",
                _indent(
                    f"Removed by the lazy-loading change in rich {row['version']} "
                    f"({row['date']}).\n\n"
                    'Use `importlib.metadata.version("rich")`. Note that `typer.__version__` '
                    "DOES still exist, which is what makes this easy to get wrong -- the two "
                    "libraries differ, and the failing one fails at runtime."
                ),
                _indent("pattern: rich.__version__", 2),
            )
        )
        (tests_dir / "project-rich-version-attr-test.yml").write_text(
            "id: project-rich-version-attr\n"
            "valid:\n"
            "  - |\n"
            "    from importlib.metadata import version\n"
            "    v = version('rich')\n"
            "  - |\n"
            "    import typer\n"
            "    v = typer.__version__\n"
            "invalid:\n"
            "  - |\n"
            "    import rich\n"
            "    v = rich.__version__\n"
        )
        written += 1

    if written != len(named):
        raise QueryError(
            f"{len(named)} rules are named in catalogs.json but {written} were generated; "
            "a named rule with no generator is a row that silently does nothing"
        )
    return written


def load_rows(path: Path) -> list[dict]:
    """Rows and facts together: both can name a rule, and `write_all` treats them alike."""
    payload = json.loads(path.read_text())
    return payload["breaking_changes"] + payload.get("current_facts", [])
